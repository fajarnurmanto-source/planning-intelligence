const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname,'../..')
test('R88 loads only on request, reuses R85 workspace and rejects unsafe gates',()=>{
 const js=fs.readFileSync(path.join(root,'public/regulatory-planning-r88.js'),'utf8')
 const html=fs.readFileSync(path.join(root,'public/development-case-r85.html'),'utf8')
 assert.match(html,/id="r88-crosswalk"/)
 assert.match(js,/credentials:'same-origin'/)
 assert.match(js,/numeric_comparison !== 'BLOCKED'/)
 assert.match(js,/review_decision !== 'NO_ACTIVE_DECISION'/)
 assert.match(js,/production_admission !== 'DENIED'/)
 assert.match(js,/JSON.stringify\(data,null,2\)/)
 assert.doesNotMatch(js,/innerHTML|insertAdjacentHTML|document.write/)
})
