const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const read=n=>fs.readFileSync(path.resolve(__dirname,'../../public',n),'utf8')
test('W3B four collapsed native task groups preserve legacy anchors and six direct assets',()=>{
 const h=read('regulatory-laravel-r70g.html')
 assert.equal((h.match(/<details[^>]*data-pi-regulatory-task=/g)||[]).length,4)
 assert.equal((h.match(/<details[^>]*data-pi-regulatory-task=[^>]*\bopen\b/g)||[]).length,0)
 for(const id of ['r72-title','r70g-documents','r74-title','r75-title','r70l-title','r70o-form','r70i-export']) assert.ok(h.includes('id="'+id+'"'))
 assert.equal((h.match(/<script\b[^>]*src="/g)||[]).length,3)
 assert.equal((h.match(/<link\b[^>]*rel="stylesheet"/g)||[]).length,3)
 assert.ok(h.includes('bukan kesetaraan seluruh fungsi legacy'))
})
