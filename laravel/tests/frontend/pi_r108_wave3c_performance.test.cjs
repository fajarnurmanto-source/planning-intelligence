const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'../..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
test('W3C uses existing case graph and separates unavailable performance quantities',()=>{
 const h=read('public/development-case-r85.html'),j=read('public/development-case-r85.js')
 const c=JSON.parse(read('resources/pi/development-case-r85.json')).case
 for(const id of ['E06','E08','E09','E10','E11','E12'])assert.ok(c.edges.some(e=>e.id===id))
 assert.match(h,/id="pi-performance-evidence"/)
 assert.match(j,/renderPerformance\(caseData\)/)
 assert.match(j,/Target dan satuan/)
 assert.match(j,/Realisasi/)
 assert.match(j,/belum tersedia bukti nilai/)
 assert.match(j,/Keluaran tidak membuktikan outcome/)
 assert.doesNotMatch(j,/innerHTML|document\.write/)
 assert.ok(h.indexOf('id="r88-results"')<h.indexOf('id="r89-panel"'))
})
